"""Replace unreliable native group lookup with explicit, verified native destinations."""
import json
import datetime
from pathlib import Path
import build_map as b
ROOT=Path(__file__).resolve().parent.parent
PAIRS=[('KT2_QuickStart','KT2_CourtArrival'),('KT2_FreeStart','KT2_FreeArrival'),('KT2_CourtReturn','KT2_HubArrival')]+[(f'KT3_0{i}_Src',f'KT3_0{i}_Dest') for i in range(3,7)]+[(f'KT_Portal_{n}',f'KT_Portal_{n}_Return') for n in ['Aim','Arena','Scenario']]+[(f'KT_Portal_{n}_Return',f'KT_Portal_{n}') for n in ['Aim','Arena','Scenario']]
# Fight Lab start rifts (tools/build_fight_lab.py start_rifts): each room's doorway pad to where its exercise begins,
# and room A's loop from the climb tower roof back to the top of the drop tower. Appended, so the button indices
# below still name the same pairs.
LAB_RIFTS=[(f'KT7_Lab_Rift_{r}_In',f'KT7_Lab_Rift_{r}_Start') for r in 'ABCD']+[('KT7_Lab_Rift_A_Loop','KT7_Lab_Rift_A_Start')]
PAIRS=PAIRS+LAB_RIFTS

def decode(v):return json.loads(v) if isinstance(v,str) else v
def main():
    m=b.Mcp();V='ValkyrieToolset.VerseToolset'
    assert m.tool(b.SCENE,'get_current_level')==b.MODULE+'/KeystrokeTrainer'
    actors=m.tool(b.SCENE,'find_actors',collision_channels=[]);by={a['label']:a['actorPath'] for a in actors}
    missing=[name for pair in PAIRS for name in pair if name not in by]
    if missing:raise RuntimeError(missing)
    backup=ROOT/'backups'/('explicit-rifts-'+datetime.datetime.now().strftime('%Y%m%d-%H%M%S'));backup.mkdir()
    journal=[]
    def note(value):
        journal.append(value);(backup/'journal.json').write_text(json.dumps(journal,indent=2))
    defs=[]
    for src,dst in PAIRS:
        defs.append(dict(source=src,destination=dst,entry=m.tool(b.ACTOR,'get_actor_transform',actor={'refPath':by[src]})['location'],exit=m.tool(b.ACTOR,'get_actor_transform',actor={'refPath':by[dst]})['location'],walk=not src.startswith('KT3_')))
    (ROOT/'shared/rift-routes.json').write_text(json.dumps(defs,indent=2))
    vec=lambda p:'vector3{' + ', '.join(f'{k.upper()} := {float(v)}' for k,v in p.items())+'}'
    source='''# Generated by tools/install_rift_router.py from the live named endpoints.
using { /UnrealEngine.com/Temporary/SpatialMath }
rift_route_def := struct<computes>:
    Entry:vector3 = vector3{}
    Exit:vector3 = vector3{}
    WalkIn:logic = true
RiftRoutes:[]rift_route_def = array{
'''+',\n'.join('    rift_route_def{Entry := '+vec(d['entry'])+', Exit := '+vec(d['exit'])+', WalkIn := '+str(d['walk']).lower()+'}' for d in defs)+'\n}\n'
    (ROOT/'verse/KeystrokeTrainer/RiftRoutes.verse').write_text(source)
    for name in ['Tags.verse','RiftRoutes.verse','RiftRouter.verse','AutoTestDevice.verse']:
        m.tool(V,'WriteFile',path=b.MODULE+'/KeystrokeTrainer/'+name,content=(ROOT/'verse/KeystrokeTrainer'/name).read_text(),bCreateIfMissing=True)
    result=m.tool(V,'BuildAll');print('BUILD',result,flush=True)
    if not isinstance(result,list) or any(d['severity']=='Error' for d in result):raise RuntimeError(result)
    def tag(ref,name,tag):
        cs=m.tool(b.ACTOR,'get_components',actor=ref)
        c=next((c for c in cs if c['refPath'].endswith('.'+name)),None)
        if c is None:c=m.tool(b.ACTOR,'add_component',owner=ref,component_type={'refPath':'/Script/VerseTags.VerseTagMarkupComponent'},name=name)
        m.tool(b.OBJ,'list_properties',instance=c)
        m.tool(b.OBJ,'set_properties',instance=c,values=json.dumps({'internalTags':{'internalTags':[{'internalTag':{'refPath':b.MODULE+'/_Verse.KeystrokeTrainer-'+tag}}]}}))
    outgoing={d['source']:d for d in defs}
    for name in sorted({n for pair in PAIRS for n in pair}):
        r={'refPath':by[name]};tag(r,'KT_RiftNode','kt_rift_node_tag');m.tool(b.OBJ,'list_properties',instance=r)
        values={'knob_TargetTeleporterGroup':'Group_None','teleporter Rift Visible':bool(name in outgoing and outgoing[name]['walk']),'enabledDuringPhase':'Always','maintain Relative Position':False,'conserve Momentum':False}
        note(dict(label=name,path=by[name],before=m.tool(b.OBJ,'get_properties',instance=r,properties=list(values)),after=values))
        m.tool(b.OBJ,'set_properties',instance=r,values=json.dumps(values))
        actual=decode(m.tool(b.OBJ,'get_properties',instance=r,properties=list(values)));assert actual==values,(name,actual)
        m.tool(b.SCENE,'save_actor',actor=r)
    # Buttons target receiving endpoints directly; no native group lookup is involved.
    indices=[0,1,3,4,5,6,7,8]
    for button_index,pair_index in enumerate(indices,1):
        src,dst=PAIRS[pair_index];button={'refPath':by[f'KT3_{button_index:02d}_Button']};s={'refPath':by[src]};d={'refPath':by[dst]}
        links=m.tool(b.DEVICE,'ListEventBindings',devicePath=s)
        for link in links:
            if link['sourceDevicePath']==button and link['targetFunction'] in ['Activate','Teleport']:
                note(dict(removedBinding=link));m.tool(b.DEVICE,'RemoveEventBinding',**link)
        link=dict(sourceDevicePath=button,sourceEvent='On Interact',targetDevicePath=d,targetFunction='Teleport')
        m.tool(b.DEVICE,'AddEventBinding',**link)
        assert link in m.tool(b.DEVICE,'ListEventBindings',devicePath=d)
        for ref in [s,d]:m.tool(b.SCENE,'save_actor',actor=ref)
    name='KT5_RiftRouter'
    if name in by:r={'refPath':by[name]}
    else:
        r=m.tool(b.DEVICE,'PlaceDevice',assetPath={'refPath':b.MODULE+'/_Verse.KeystrokeTrainer-kt_rift_router_device'},transform=b.xform(0,-59648,-700))  # below the floor, clear of the hub arrival
        m.tool(b.ACTOR,'set_label',actor=r,label=name);note(dict(created=name,path=r['refPath']))
    tag(r,'KT_RiftRouter','kt_rift_router_tag');m.tool(b.SCENE,'save_actor',actor=r)
    print('Explicit rifts installed; journal:',backup,flush=True)
if __name__=='__main__':main()
