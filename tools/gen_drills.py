"""Generate verse/KeystrokeTrainer/DrillCatalog.verse from shared/drills.json.

shared/drills.json is the one place drills are defined; the map (Verse) and the companion app
(Python) both read from it. Run this after every edit to the JSON:

    python tools/gen_drills.py            # write the file
    python tools/gen_drills.py --check    # exit 1 if the Verse file is stale (for CI / agents)
"""

import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "shared" / "drills.json"
OUT = ROOT / "verse" / "KeystrokeTrainer" / "DrillCatalog.verse"
CHECK_KINDS = {"wall_check", "stand_level", "climb", "volume", "exposure", "target_hit"}
TARGETS = {"gun", "pickaxe"}
LANE_KINDS = {"gap", "flat"}


def verse_str(s):
    if any(c in s for c in '"{}\\\n'):
        raise ValueError(f"unsupported character in {s!r}")
    return f'"{s}"'


def validate(data):
    for d in data["drills"]:
        g = d.get("edit_guide")
        if g:
            if not g["tiles"] or any(not 0 <= v <= 8 for v in g["tiles"]) or g["start"] not in g["tiles"] or g["end"] not in g["tiles"]:
                raise ValueError(f"{d['id']}: edit_guide tiles must be 0..8 and include start and end")
    actions = set(data["actions"])
    seen = set()
    principles = {p["id"] for p in data.get("principles", [])}
    live_ids = {d["id"] for d in data["drills"] if not d.get("retired")}
    in_section = set()
    for sec in data.get("sections", []):
        for did in sec["drills"]:
            if did not in live_ids:
                raise ValueError(f"section {sec['id']}: drill {did!r} is unknown or retired")
            if did in in_section:
                raise ValueError(f"drill {did!r} is in more than one section")
            in_section.add(did)
    for p in data.get("principles", []):
        for k in ("name", "rule", "why", "creative"):
            verse_str(p[k])
    for d in data["drills"]:
        if d["id"] in seen:
            raise ValueError(f"duplicate drill id {d['id']}")
        seen.add(d["id"])
        for a in d["steps"]:
            if a not in actions:
                raise ValueError(f"{d['id']}: unknown action {a!r}")
        for c in d["checks"]:
            if c["kind"] not in CHECK_KINDS:
                raise ValueError(f"{d['id']}: unknown check kind {c['kind']!r}")
            if not 0 <= c["step"] < len(d["steps"]):
                raise ValueError(f"{d['id']}: check step {c['step']} out of range")
            if c["kind"] == "target_hit" and c.get("target") not in TARGETS:
                raise ValueError(f"{d['id']}: target_hit needs target gun or pickaxe")
            if "cell" in c and len(c["cell"]) != 3:
                raise ValueError(f"{d['id']}: cell must be [right, forward, up]")
        for k in ("tip", "why", "reflect"):
            verse_str(d.get(k, ""))
        for alt in d.get("accepts", []):
            for act in alt:
                if act not in actions:
                    raise ValueError(f"{d['id']}: accepts has unknown action {act!r}")
        verse_str(d.get("basis", ""))
        if d.get("loadout", "any") not in ("any", "melee"):
            raise ValueError(f"{d['id']}: loadout must be any or melee")
        if d.get("principle", "") and d["principle"] not in principles:
            raise ValueError(f"{d['id']}: unknown principle {d['principle']!r}")
        if len(d.get("advance", [1, 0, 0])) != 3:
            raise ValueError(f"{d['id']}: advance must be [right, forward, up]")
        if d.get("lane", {}).get("kind", "flat") not in LANE_KINDS:
            raise ValueError(f"{d['id']}: unknown lane kind")


def render(data):
    out = [
        "# GENERATED by tools/gen_drills.py from shared/drills.json. Do not edit by hand.",
        "",
        "drill_check<public> := struct<computes>:",
        "    Step<public>:int = 0",
        "    # wall_check | stand_level | climb | volume | exposure (no damage taken) | target_hit (gun or pickaxe hit lands)",
        '    Kind<public>:string = ""',
        "    # Grid cell relative to the drill device: [right, forward, up]. Forward = device +X.",
        "    Cell<public>:[]int = array{0, 0, 0}",
        '    Dir<public>:string = ""',
        '    Volume<public>:string = ""',
        '    # gun | pickaxe, for target_hit checks',
        '    Target<public>:string = ""',
        "",
        "principle_def<public> := struct<computes>:",
        '    Id<public>:string = ""',
        '    Name<public>:string = ""',
        '    Rule<public>:string = ""',
        '    Why<public>:string = ""',
        '    # How much room the player has to play their own way inside the rule.',
        '    Creative<public>:string = ""',
        "",
        "drill_def<public> := struct<computes>:",
        '    Id<public>:string = ""',
        "    # Station code on signs and cues, e.g. B2.",
        '    Code<public>:string = ""',
        "    Tier<public>:int = 1",
        '    Name<public>:string = ""',
        "    Steps<public>:[]string = array{}",
        "    Reps<public>:int = 10",
        "    Checks<public>:[]drill_check = array{}",
        "    # Cells between reps, [right, forward, up]; each rep gets a fresh track.",
        "    Advance<public>:[]int = array{1, 0, 0}",
        "    # One coaching sentence for the results card when a set is not clean.",
        '    Tip<public>:string = ""',
        "    # Id of the principle this drill trains, one plain-language reason, and a question for after the set.",
        '    Principle<public>:string = ""',
        '    Why<public>:string = ""',
        '    Reflect<public>:string = ""',
        "",
        "ActionVocabulary<public>:[]string = array{" + ", ".join(verse_str(a) for a in data["actions"]) + "}",
        "",
        "PrincipleCatalog<public>:[]principle_def = array{",
    ]
    out.append(",\n".join(
        "    principle_def{" + ", ".join(f"{k.capitalize()} := {verse_str(p[k])}" for k in ("id", "name", "rule", "why", "creative")) + "}"
        for p in data.get("principles", [])))
    out += ["}", "", "DrillCatalog<public>:[]drill_def = array{"]
    rows = []
    for d in data["drills"]:
        checks = []
        for c in d["checks"]:
            fields = [f"Step := {c['step']}", f"Kind := {verse_str(c['kind'])}"]
            if "cell" in c:
                fields.append("Cell := array{" + ", ".join(str(v) for v in c["cell"]) + "}")
            if "dir" in c:
                fields.append(f"Dir := {verse_str(c['dir'])}")
            if "volume" in c:
                fields.append(f"Volume := {verse_str(c['volume'])}")
            if "target" in c:
                fields.append(f"Target := {verse_str(c['target'])}")
            checks.append("drill_check{" + ", ".join(fields) + "}")
        fields = [
            f"Id := {verse_str(d['id'])}",
            f"Code := {verse_str(d.get('code', ''))}",
            f"Tier := {d['tier']}",
            f"Name := {verse_str(d['name'])}",
            "Steps := array{" + ", ".join(verse_str(s) for s in d["steps"]) + "}",
            f"Reps := {d['reps']}",
            "Checks := array{" + ", ".join(checks) + "}",
            "Advance := array{" + ", ".join(str(v) for v in d.get("advance", [1, 0, 0])) + "}",
            f"Tip := {verse_str(d.get('tip', ''))}",
            f"Principle := {verse_str(d.get('principle', ''))}",
            f"Why := {verse_str(d.get('why', ''))}",
            f"Reflect := {verse_str(d.get('reflect', ''))}",
        ]
        rows.append("    drill_def{" + ", ".join(fields) + "}")
    out.append(",\n".join(rows))
    out.append("}")
    out += [
        "",
        "FindDrill<public>(Id:string)<decides><transacts>:drill_def =",
        "    (for (D : DrillCatalog, D.Id = Id) { D })[0]",
        "",
        "action_hint<public> := struct<computes>:",
        '    Action<public>:string = ""',
        '    Text<public>:string = ""',
        "",
        "ActionHints<public>:[]action_hint = array{" + ", ".join(
            f"action_hint{{Action := {verse_str(a)}, Text := {verse_str(t)}}}" for a, t in data.get("action_hints", {}).items()) + "}",
        "",
        "ActionHintFor<public>(Action:string)<decides><transacts>:string =",
        "    (for (H : ActionHints, H.Action = Action) { H.Text })[0]",
        "",
        "section_def<public> := struct<computes>:",
        '    Id<public>:string = ""',
        '    Name<public>:string = ""',
        '    Blurb<public>:string = ""',
        '    # Drill ids played in this order from the section pad.',
        '    Drills<public>:[]string = array{}',
        "",
        "SectionCatalog<public>:[]section_def = array{" + ", ".join(
            "section_def{Id := " + verse_str(x["id"]) + ", Name := " + verse_str(x["name"]) + ", Blurb := " + verse_str(x.get("blurb", ""))
            + ", Drills := array{" + ", ".join(verse_str(i) for i in x["drills"]) + "}}" for x in data.get("sections", [])) + "}",
        "",
        "FindSection<public>(Id:string)<decides><transacts>:section_def =",
        "    (for (S : SectionCatalog, S.Id = Id) { S })[0]",
        "",
        "# Crosshair guide for an edit drill. Tiles index the 3x3 wall grid as the player faces it:",
        "# row * 3 + col, row 0 bottom to 2 top, col 0 left to 2 right. Start and End are the tiles the",
        "# crosshair should rest on when edit is pressed and when the drag is released.",
        "edit_guide<public> := struct<computes>:",
        '    DrillId<public>:string = ""',
        "    Tiles<public>:[]int = array{}",
        "    Start<public>:int = 4",
        "    End<public>:int = 4",
        "    GuidedReps<public>:int = 5",
        '    Note<public>:string = ""',
        "",
        "EditGuides<public>:[]edit_guide = array{" + ", ".join(
            "edit_guide{DrillId := " + verse_str(d["id"]) + ", Tiles := array{" + ", ".join(str(v) for v in d["edit_guide"]["tiles"])
            + "}, Start := " + str(d["edit_guide"]["start"]) + ", End := " + str(d["edit_guide"]["end"])
            + ", GuidedReps := " + str(d["edit_guide"].get("guided_reps", 5)) + ", Note := " + verse_str(d["edit_guide"].get("note", "")) + "}"
            for d in data["drills"] if "edit_guide" in d) + "}",
        "",
        "FindEditGuide<public>(Id:string)<decides><transacts>:edit_guide =",
        "    (for (G : EditGuides, G.DrillId = Id) { G })[0]",
        "",
        "FindPrinciple<public>(Id:string)<decides><transacts>:principle_def =",
        "    (for (P : PrincipleCatalog, P.Id = Id) { P })[0]",
        "",
        "ChecksForStep<public>(Drill:drill_def, Step:int)<transacts>:[]drill_check =",
        "    for (C : Drill.Checks, C.Step = Step) { C }",
        "",
    ]
    adaptive = data.get("adaptive_edit", {})
    out += ["edit_route<public> := struct<computes>:", '    Name<public>:string = ""', "    Tiles<public>:[]int = array{}", ""]
    for key, value in adaptive.items():
        if key != "routes":
            out.append("EditCue_" + key + "<public>:string = " + verse_str(value))
    routes = adaptive.get("routes", [])
    if len(routes) != 5:
        raise ValueError("adaptive_edit requires four corner routes followed by the center window")
    for route in routes:
        if not route["tiles"] or len(set(route["tiles"])) != len(route["tiles"]) or any(not 0 <= t <= 8 for t in route["tiles"]):
            raise ValueError("invalid adaptive edit route")
    out.append("EditRoutes<public>:[]edit_route = array{" + ", ".join(
        "edit_route{Name := " + verse_str(r["name"]) + ", Tiles := array{" + ", ".join(map(str,r["tiles"])) + "}}" for r in routes) + "}")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = json.loads(SRC.read_text(encoding="utf-8"))
    validate(data)
    text = render(data)
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run python tools/gen_drills.py")
            return 1
        print("DrillCatalog.verse is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(data['drills'])} drills)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
