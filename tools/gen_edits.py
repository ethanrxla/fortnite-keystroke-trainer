"""Generate verse/KeystrokeTrainer/EditCatalog.verse from shared/edits.json (the library of real edits, every piece).

    python tools/gen_edits.py [--check]

Pieces: wall (3 x 3 tiles), floor / stairs / roof (2 x 2 tiles); shared/edits.json "pieces" gives each one's grid and its
slot in the build hotbar. EditGuide.verse ranks the suggested edits of the piece the player is placing. Change shapes in
shared/edits.json, rerun this, copy the .verse into the island and build. Never hand-edit EditCatalog.verse.

It also writes EditPatterns.verse: every shape in the library (suggested or not), the pattern table BuildPieces.verse
matches a confirmed edit against (tile mask, ramp path, the Fortnite result class). Never hand-edit it either.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "shared" / "edits.json"
OUT = ROOT / "verse" / "KeystrokeTrainer" / "EditCatalog.verse"
OUT_PATTERNS = ROOT / "verse" / "KeystrokeTrainer" / "EditPatterns.verse"
CANONICAL = {"wall": "wall", "floor": "floor", "stairs": "ramp", "roof": "cone"}
VERSE_NAME = {"wall": "KTWallEdits", "floor": "KTFloorEdits", "stairs": "KTStairsEdits", "roof": "KTRoofEdits"}


def mirror_tiles(tiles, cols=3):
    """Left/right mirror of tile indexes for a grid `cols` wide (column c -> cols - 1 - c)."""
    return [t - 2 * (t % cols) + (cols - 1) for t in tiles]


def pieces(data):
    """{piece: {cols, rows, list, build_slot}} with the wall defaults when an older file has no `pieces` block."""
    return data.get("pieces") or {"wall": {"cols": 3, "rows": 3, "list": "wall_edits", "build_slot": 0}}


def edits_for(data, piece="wall"):
    return data.get(pieces(data)[piece]["list"], [])


def suggested(data, piece="wall"):
    return [e for e in edits_for(data, piece) if e["suggest"]]


# Ramp arrows: for each of the 4 tiles, the way its stairs climb. 0 = no stairs, 1 = away (far), 2 = right,
# 3 = toward the player (near), 4 = left. Each tile points at the next tile of its stroke; a stroke's last tile keeps
# the stroke's last direction. Same rule in companion/keystroke_lab/build_pieces.py and BuildPieces.verse.
STEP_DIR = {2: 1, 1: 2, -2: 3, -1: 4}


def ramp_arrows(strokes, tiles=4):
    arrows = [0] * tiles
    for stroke in strokes:
        for i, t in enumerate(stroke):
            a, b = (stroke[i], stroke[i + 1]) if i + 1 < len(stroke) else (stroke[i - 1], stroke[i])
            arrows[t] = STEP_DIR[b - a]
    return arrows


def verse_str(s):
    return chr(34) + s.replace(chr(92), chr(92) * 2).replace(chr(34), chr(92) + chr(34)) + chr(34)


def validate(data):
    seen = set()
    for piece, meta in pieces(data).items():
        cols, rows = meta["cols"], meta["rows"]
        edits = edits_for(data, piece)
        by_id = {}
        for e in edits:
            if e["id"] in seen:
                raise ValueError(f"duplicate edit id {e['id']}")
            seen.add(e["id"])
            by_id[e["id"]] = e
            tiles = e["tiles"]
            if piece == "stairs" and not tiles:
                continue
            if not tiles or any(not isinstance(t, int) or not 0 <= t < cols * rows for t in tiles) or len(set(tiles)) != len(tiles):
                raise ValueError(f"{e['id']}: tiles must be distinct ints 0..{cols * rows - 1} for a {piece}")
            if e["name"] in data.get("not_edits", []):
                raise ValueError(f"{e['id']}: {e['name']} is listed under not_edits")
            if e.get("tier") == "rare" and e.get("suggest"):
                raise ValueError(f"{e['id']}: a rare edit is never suggested (the guide shows its `prefer` edit)")
            for stroke in e.get("strokes") or []:
                if len(stroke) < 2 or any(abs(b - a) not in (1, cols) or (abs(b - a) == 1 and min(a, b) % cols == cols - 1)
                                          for a, b in zip(stroke, stroke[1:])):
                    raise ValueError(f"{e['id']}: each ramp stroke steps to a neighbouring tile")
        for e in edits:
            if e.get("prefer") and e["prefer"] not in by_id:
                raise ValueError(f"{e['id']}: prefer {e['prefer']} is not a {piece} edit")
        for e in edits:
            mirrored = set(mirror_tiles(e["tiles"], cols))
            if mirrored == set(e["tiles"]):
                continue
            partner = by_id.get(e.get("mirror_of") or "")
            if partner is None:
                raise ValueError(f"{e['id']}: asymmetric {piece} shape needs a mirror_of partner")
            if set(partner["tiles"]) != mirrored or partner.get("mirror_of") != e["id"]:
                raise ValueError(f"{e['id']}: mirror_of {partner['id']} is not its left/right mirror")
            if bool(partner["suggest"]) != bool(e["suggest"]):
                raise ValueError(f"{e['id']} and {partner['id']} must both be suggested or both not")


def render(data):
    lines = [
        "# GENERATED by tools/gen_edits.py from shared/edits.json. Do not edit by hand.",
        "# The edits the guide may recommend (suggest = true), per piece, tiles in drag order. Wall tiles are 0-8 from the",
        "# bottom-left; floor, stairs and roof tiles are 0-3 (0 near-left, 1 near-right, 2 far-left, 3 far-right).",
        "# The order within each array is the index order of that piece's rows in EditPolicy.verse.",
        "",
    ]
    for piece, meta in pieces(data).items():
        name = VERSE_NAME[piece]
        shapes = suggested(data, piece)
        lines.append(f"# {piece}: grid {meta['cols']} x {meta['rows']}, build hotbar slot {meta.get('build_slot')}")
        if not shapes:
            lines.append(f"{name}<public>:[]kt_edit_shape = array{{}}")
        else:
            lines.append(f"{name}<public>:[]kt_edit_shape = array:")
            for e in shapes:
                tiles = ", ".join(str(t) for t in e["tiles"])
                lines.append(f"    kt_edit_shape{{Id := {verse_str(e['id'])}, Name := {verse_str(e['name'])}, Tiles := array{{{tiles}}}}}")
        lines.append("")
    return chr(10).join(lines)


def render_patterns(data):
    lines = [
        "# GENERATED by tools/gen_edits.py from shared/edits.json. Do not edit by hand.",
        "# Every edit shape in the library: the pattern table kt_build_piece.Confirm matches against (BuildPieces.verse).",
        "# Mask = sum of 2^tile over the selected tiles. Path = the tiles in drag order (for a ramp, the climb order,",
        "# bottom first). ResultClass = the Fortnite build class the piece becomes (PBWA_W1_<class>), \"\" if unknown.",
        "# Arrows (ramps only, matched instead of the mask): per tile 0 none, 1 away, 2 right, 3 toward you, 4 left.",
        "# Tier: common, situational or rare; Prefer: the common edit the guide shows instead of a rare one.",
        "",
        "KTEditPatterns<public>:[]kt_edit_pattern = array:",
    ]
    for piece, meta in pieces(data).items():
        keep_path = meta.get("edit_semantics") == "keep_path"
        for e in edits_for(data, piece):
            strokes = e.get("strokes") or ([e["path"]] if e.get("path") else None)
            tiles = [t for st in strokes for t in st] if strokes else e["tiles"]
            if not tiles or (keep_path and not strokes):
                continue
            mask = sum(1 << t for t in set(tiles))
            path = ", ".join(str(t) for t in tiles)
            arrows = ", ".join(str(a) for a in ramp_arrows(strokes, meta["cols"] * meta["rows"])) if keep_path else ""
            suggest = "true" if e.get("suggest") else "false"
            lines.append(f"    kt_edit_pattern{{Id := {verse_str(e['id'])}, Kind := {verse_str(CANONICAL[piece])}, Mask := {mask}, "
                         f"Path := array{{{path}}}, Arrows := array{{{arrows}}}, "
                         f"ResultClass := {verse_str(e.get('result_class') or '')}, Suggest := {suggest}, "
                         f"Tier := {verse_str(e.get('tier') or 'situational')}, Prefer := {verse_str(e.get('prefer') or '')}}}")
    lines.append("")
    return chr(10).join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if EditCatalog.verse is out of date")
    args = ap.parse_args()
    data = json.loads(SRC.read_text(encoding="utf-8"))
    validate(data)
    outputs = {OUT: render(data), OUT_PATTERNS: render_patterns(data)}
    if args.check:
        stale = [p.name for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"{', '.join(stale)} out of date; run python tools/gen_edits.py")
            return 1
        return 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8", newline="\n")
    summary = ", ".join(f"{p}: {len(suggested(data, p))}/{len(edits_for(data, p))} suggested" for p in pieces(data))
    print(f"wrote {OUT.name} ({summary}) and {OUT_PATTERNS.name} ({outputs[OUT_PATTERNS].count('kt_edit_pattern{')} patterns)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
