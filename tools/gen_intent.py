"""Generate verse/KeystrokeTrainer/EditIntent.verse from shared/edit-intent.json (the player's aim map).

    python tools/gen_intent.py [--check]

The companion overlay reads shared/edit-intent.json directly (edit_ranker.IntentMap). The in-map guide
(EditGuide.verse KTRankEdits) gets the same rules through this file: KTIntentEdit(Kind, Aim) gives the edit the aim map
names for the crosshair position, and KTRankEdits shows it first. Walls only for now: the map's floors and roofs use
their own tile frame (near / far from the player), which is not yet checked against the companion's. Never hand-edit
EditIntent.verse; change shared/edit-intent.json and rerun this.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "shared" / "edit-intent.json"
OUT = ROOT / "verse" / "KeystrokeTrainer" / "EditIntent.verse"


def num(x):
    return f"{float(x):.2f}"


def wall_function(spec):
    """Junctions (within junction_radius of an inner corner) win over zones, zones over the tile rule: the same order
    as edit_ranker.IntentMap."""
    n = 3
    lines = ["KTIntentWall<public>(Aim:vector2)<transacts>:string =",
             f"    if (Aim.X < 0.0 or Aim.X >= {num(n)} or Aim.Y < 0.0 or Aim.Y >= {num(n)}):",
             "        return \"\""]
    r = float(spec.get("junction_radius", 0))
    for key, edit in (spec.get("junctions") or {}).items():
        x, y = (float(v) for v in key.split(","))
        lines += [f"    if (Distance(Aim, vector2{{X := {num(x)}, Y := {num(y)}}}) <= {num(r)}):", f"        return \"{edit}\""]
    # Later zones win in IntentMap (each overwrites), so test them last-first here.
    for u0, v0, u1, v1, edit in reversed(spec.get("zones") or []):
        lines += [f"    if (Aim.X >= {num(u0)}, Aim.X < {num(u1)}, Aim.Y >= {num(v0)}, Aim.Y < {num(v1)}):",
                  f"        return \"{edit}\""]
    tiles = ", ".join(f"\"{t}\"" for t in spec["tiles"])
    lines.append(f"    Tiles:[]string = array{{{tiles}}}")
    lines.append(f"    Col := if (C := Floor[Aim.X]) then Clamp(C, 0, {n - 1}) else 0")
    lines.append(f"    Row := if (R := Floor[Aim.Y]) then Clamp(R, 0, {n - 1}) else 0")
    lines.append(f"    if (T := Tiles[Row * {n} + Col]) then T else \"\"")
    return "\n".join(lines)


def render(data):
    head = ["# GENERATED by tools/gen_intent.py from shared/edit-intent.json. Do not edit by hand.",
            "# The player's aim map: which edit the guide shows for where the crosshair is on the piece (Aim in tiles,",
            "# X right, Y up from the bottom-left as the player sees it). Same rules as the companion (edit_ranker.IntentMap).",
            "",
            "using { /UnrealEngine.com/Temporary/SpatialMath }",
            "",
            "# The aim map's edit id for this piece and aim point, \"\" when the map has none (then Jev's ranking alone decides).",
            "KTIntentEdit<public>(Kind:string, Aim:vector2)<transacts>:string =",
            "    if (Kind = \"wall\") then KTIntentWall(Aim) else \"\"",
            ""]
    return "\n".join(head) + "\n" + wall_function(data["wall"]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if EditIntent.verse is out of date")
    args = ap.parse_args()
    text = render(json.loads(SRC.read_text(encoding="utf-8")))
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.name} is out of date: run python tools/gen_intent.py")
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
